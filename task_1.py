class Yarn:
    """
    Базовый класс, представляющий моток пряжи.

    Атрибуты:
        name (str): название пряжи.
        fiber_type (str): тип волокна (например, 'шерсть', 'хлопок', 'акрил').
        weight (float): вес мотка в граммах.
        length (float): длина нити в метрах.
        color (str): цвет пряжи.
        _remaining_length (float): оставшаяся длина нити в метрах. Непубличный атрибут,
                                    изменяется только через метод use_yarn.
    """

    def __init__(self, name: str, fiber_type: str, weight: float, length: float, color: str) -> None:
        """
        Инициализирует моток пряжи с заданными параметрами.

        Аргументы:
            name: название пряжи.
            fiber_type: тип волокна.
            weight: вес мотка в граммах.
            length: длина нити в метрах.
            color: цвет пряжи.
        """
        self.name = name
        self.fiber_type = fiber_type
        self.weight = weight
        self.length = length
        self.color = color
        self._remaining_length = length  # изначально остаток равен всей длине

    def __str__(self) -> str:
        """Возвращает удобочитаемое строковое представление пряжи."""
        ...

    def __repr__(self) -> str:
        """Возвращает формальное строковое представление для воссоздания объекта."""
        ...

    def calculate_yardage(self) -> float:
        """
        Вычисляет метраж (количество метров на 100 грамм).

        Returns:
            Длина в метрах на 100 г пряжи.
        """
        ...

    def use_yarn(self, meters: float) -> None:
        """
        Использует указанное количество метров пряжи, уменьшая остаток.

        Аргументы:
            meters: количество метров, которое нужно использовать.
        """
        ...

    def get_fiber_type(self) -> str:
        """
        Возвращает тип волокна пряжи.

        Returns:
            Строка с типом волокна.
        """
        ...

    def get_remaining_length(self) -> float:
        """
        Возвращает оставшуюся длину нити.

        Returns:
            Оставшаяся длина в метрах.
        """
        ...


